# main.py
# ─────────────────────────────────────────────
# 역할: 퀴즈 게임 프로그램이 시작되는 입구 파일이다.
# 실제 메뉴와 실행 흐름은 game.py의 QuizGame 클래스가 담당하며,
# 이 파일은 게임 객체를 만들고 실행하는 두 가지 일만 한다.
# 실행 방법: 터미널에서 python3 main.py
# ─────────────────────────────────────────────

from game import QuizGame  # game.py 파일에서 QuizGame 클래스 설계도를 가져온다.


if __name__ == "__main__":
    # __name__은 파이썬이 각 파일에 자동으로 넣어 주는 특별한 변수다.
    # 이 값이 "__main__"이라는 것은 이 파일을 직접 실행했다는 뜻이다.
    # 따라서 다른 파일이 main.py를 import할 때는 아래 실행 코드가 자동으로 동작하지 않는다.
    game = QuizGame()  # 클래스라는 설계도로 실제 게임 객체를 만들며, 이때 __init__이 실행된다.
    game.run()  # 만든 객체의 run 메서드를 호출해 메뉴 반복을 시작한다.
